type backendUse struct {
	pool        string
	clientTLS   any
	iRules      []any
	persistence []any
}

func (u backendUse) applyTo(svc *Service) {
	if u.clientTLS != nil {
		svc.ClientTLS = u.clientTLS
	}
	svc.IRules = append(svc.IRules, u.iRules...)
	if len(u.persistence) > 0 {
		svc.PersistenceMethods = u.persistence
	}
}

// useBackend adds the pool of a backend to the application, with its monitor and TLS profile, once, and tells what a
// service using it carries. It is false when the backend is not known: the service referencing it from is left out.
// udp tells the service is an udp one, which can't send the proxy protocol header.
func (r *renderer) useBackend(a *appRender, from proto.Message, backendUUID string, udp bool) (backendUse, bool) {
	b, ok := r.in.Backends[backendUUID]
	backendKey := ResourceKey{TypeUrl: helpers.TypeUrl[*backend.Backend](), UUID: backendUUID}
	if !ok {
		r.res.missing(from, backendKey)
		return backendUse{}, false
	}
	opts := unpackOptions[*f5_backendopts.BackendOptions](&r.res, b, b.GetTypedOptions())
	if b.GetConnectTimeout() != nil {
		r.res.warn(b, "connect_timeout has no F5 pool equivalent, it is ignored")
	}

	poolName := PoolName(backendUUID)
	use := backendUse{pool: poolName}
	mode, hashed := lbMode(b.GetLbPolicy())
	if opts.GetLbMode() != "" {
		mode, hashed = opts.GetLbMode(), false
	}
	if hashed {
		r.res.warn(b, fmt.Sprintf("lb_policy %s has no F5 equivalent, %s with source-address persistence is used",
			b.GetLbPolicy(), mode))
		use.persistence = []any{persistenceSourceAddress}
	}
	if b.GetEnableTls() {
		use.clientTLS = ClientTLSName(backendUUID)
	}
	if b.GetEnableProxyProtocol() {
		use.iRules = r.addProxySend(a, b, poolName, udp)
	}
	if _, done := a.app.Objects[poolName]; done {
		return use, true
	}

	p := &Pool{
		Class:             classPool,
		Remark:            remark(b.GetName()),
		LoadBalancingMode: mode,
		SlowRampTime:      secondsOrZero(opts.GetSlowRampTime()),
		Members:           r.poolMembers(from, b),
	}
	r.addMonitors(a, b, p, opts)
	if b.GetEnableTls() {
		r.addClientTLS(a, b)
	}
	a.app.Objects[poolName] = p
	r.res.Pools = append(r.res.Pools, PoolRef{BackendUUID: backendUUID, Tenant: r.in.Tenant, App: a.name, Pool: poolName})
	return use, true
}

// AgentDiscovers tells the agent resolves the endpoints of a backend itself. EDS has no F5 equivalent, and BIG-IP FQDN
// members only use the DNS servers of the device, not the nameservers of the backend.
func AgentDiscovers(b *backend.Backend) bool {
	return b.GetEds() != nil || len(b.GetDns().GetNameservers()) > 0
}

// poolMembers gives the static addresses of the backend, its DNS name for the BIG-IP to resolve, or the endpoints the
// agent discovered. A backend not discovered yet is reported missing.
func (r *renderer) poolMembers(from proto.Message, b *backend.Backend) []Member {
	if AgentDiscovers(b) {
		endpoints, discovered := r.in.Endpoints[b.GetUUID()]
		if !discovered {
			r.res.missing(from, ResourceKey{TypeUrl: helpers.TypeUrl[*backend.Backend](), UUID: b.GetUUID()})
		}
		return members(endpoints)
	}
	if b.GetDns() != nil {
		return []Member{r.fqdnMember(b)}
	}
	return members(b.GetIpAddrGroup().GetIpAddresses())
}

// fqdnMember lets the BIG-IP resolve the DNS name of the backend at its refresh rate. A BIG-IP FQDN member queries a
// single record type.
func (r *renderer) fqdnMember(b *backend.Backend) Member {
	family := b.GetDns().GetLookupFamily()
	addressFamily := addressFamilyIPv4
	if family == backend.DNS_V6_ONLY {
		addressFamily = addressFamilyIPv6
	}
	singleFamily := family == backend.DNS_V4_ONLY || family == backend.DNS_V6_ONLY
	if !singleFamily {
		r.res.warn(b, fmt.Sprintf("lookup_family %s has no F5 equivalent, the BIG-IP queries A records only", family))
	}
	queryInterval := uint64(math.Ceil(b.GetRefreshRate().AsDuration().Seconds()))
	return Member{
		ServicePort:      b.GetDns().GetPort(),
		AddressDiscovery: addressDiscoveryFQDN,
		Hostname:         b.GetDns().GetHost(),
		AutoPopulate:     true,
		AddressFamily:    addressFamily,
		QueryInterval:    max(queryInterval, 1),
		ShareNodes:       true,
	}
}

func (r *renderer) addProxySend(a *appRender, b *backend.Backend, poolName string, udp bool) []any {
	if udp {
		r.res.warn(b, "proxy protocol is not sent to the endpoints of an udp virtual server")
		return nil
	}
	if b.GetProxyProtocolVersion() == backend.Backend_V2 {
		r.res.warn(b, "proxy protocol v2 is not generated by the F5 agent, v1 is sent")
	}
	name := IRuleName(iRulePurposeProxySend, b.GetUUID())
	a.app.Objects[name] = &IRule{Class: classIRule, IRule: proxySendIRule(r.objectPath(a, poolName))}
	return []any{name}
}

func (r *renderer) objectPath(a *appRender, name string) string {
	return "/" + r.in.Tenant + "/" + a.name + "/" + name
}

func (r *renderer) addMonitors(a *appRender, b *backend.Backend, p *Pool, opts *f5_backendopts.BackendOptions) {
	if len(opts.GetMonitors()) > 0 {
		for _, path := range opts.GetMonitors() {
			p.Monitors = append(p.Monitors, BigipRef{Bigip: path})
		}
		return
	}
	m, warnings := renderMonitor(b)
	for _, warning := range warnings {
		r.res.warn(b, warning)
	}
	if m == nil {
		return
	}
	a.app.Objects[MonitorName(b.GetUUID())] = m
	p.Monitors = []any{UseRef{Use: MonitorName(b.GetUUID())}}
}

func (r *renderer) addClientTLS(a *appRender, b *backend.Backend) {
	tlsClient := &TLSClient{Class: classTLSClient, ServerName: b.GetSni()}
	if b.GetCa() != "" {
		a.app.Objects[CABundleName(b.GetUUID())] = &CABundle{Class: classCABundle, Bundle: b.GetCa()}
		tlsClient.ValidateCertificate = true
		tlsClient.TrustCA = UseRef{Use: CABundleName(b.GetUUID())}
	}
	a.app.Objects[ClientTLSName(b.GetUUID())] = tlsClient
}

// lbMode maps a flock lb policy to an AS3 load balancing mode; hashed tells the policy is a consistent hash, which
// F5 pools don't have.
func lbMode(policy backend.Backend_LbPolicy) (mode string, hashed bool) {
	switch policy {
	case backend.Backend_WEIGHTED_ROUND_ROBIN:
		return lbModeRatio, false
	case backend.Backend_LEAST_REQUEST:
		return lbModeLeastConnections, false
	case backend.Backend_WEIGHTED_LEAST_REQUEST:
		return lbModeRatioLeastConnections, false
	case backend.Backend_RING_HASH, backend.Backend_MAGLEV:
		return lbModeLeastConnections, true
	default:
		return lbModeRoundRobin, false
	}
}

// members groups the endpoints sharing a port and a weight in one AS3 member, in a stable order.
func members(endpoints []*core.IPAddr) []Member {
	type group struct {
		port  uint32
		ratio uint32
	}
	addresses := map[group][]string{}
	for _, endpoint := range endpoints {
		g := group{port: endpoint.GetPort(), ratio: endpoint.GetLoadBalancingWeight()}
		addresses[g] = append(addresses[g], endpoint.GetIp())
	}
	result := make([]Member, 0, len(addresses))
	for g, ips := range addresses {
		slices.Sort(ips)
		// shared nodes live in /Common: BIG-IP refuses one address as a node of two partitions
		result = append(result, Member{ServicePort: g.port, ServerAddresses: slices.Compact(ips), Ratio: g.ratio, ShareNodes: true})
	}
	slices.SortFunc(result, func(a, b Member) int {
		return cmp.Or(cmp.Compare(a.ServicePort, b.ServicePort), cmp.Compare(a.Ratio, b.Ratio))
	})
	return result
}
