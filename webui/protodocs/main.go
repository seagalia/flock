// Command protodocs writes the proto field comments, the valid extension kinds of every Any field and the defaults the
// controller fills as TypeScript for the webui, because protobuf-es strips comments from its embedded descriptors and
// the defaults live in Go (ProvDefault). It reads the embedded protoset, so
// make generate runs it after buf build has rewritten protoset.bin.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"slices"
	"strings"

	"github.com/jhump/protoreflect/desc" //nolint:staticcheck // protoset hands out jhump/protoreflect descriptors

	"github.com/seagalia/flock/cli/protoset"
)

// the extension kinds an Any field accepts are the message names its proto comment lists
var extensionKindPattern = regexp.MustCompile(`flock\.extensions\.[A-Za-z0-9_.]+`)

const anyFullName = "google.protobuf.Any"

type protoDocs struct {
	FieldDocs      map[string]string
	ExtensionKinds map[string][]string
	FieldDefaults  map[string]string
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: protodocs <output.ts>")
		os.Exit(2)
	}
	docs, err := collectDocs()
	if err != nil {
		fmt.Fprintln(os.Stderr, "protodocs:", err)
		os.Exit(1)
	}
	err = os.WriteFile(os.Args[1], []byte(render(docs)), 0o644)
	if err != nil {
		fmt.Fprintln(os.Stderr, "protodocs:", err)
		os.Exit(1)
	}
}

func collectDocs() (protoDocs, error) {
	_, files, err := protoset.GetAllInfo()
	if err != nil {
		return protoDocs{}, err
	}
	docs := protoDocs{FieldDocs: map[string]string{}, ExtensionKinds: map[string][]string{}, FieldDefaults: map[string]string{}}
	for _, file := range files {
		isModel := strings.HasPrefix(file.GetPackage(), "flock.api.config.") ||
			strings.HasPrefix(file.GetPackage(), "flock.extensions.")
		// RegisterVipRequest is the one request the dashboard edits as a form, the create way of a VIP from the ipam
		isFormRequest := file.GetPackage() == "flock.services.vip.v1"
		if !isModel && !isFormRequest {
			continue
		}
		for _, message := range file.GetMessageTypes() {
			collectMessage(message, docs)
		}
	}
	collectDefaults(docs.FieldDefaults)
	return docs, nil
}

func collectMessage(message *desc.MessageDescriptor, docs protoDocs) {
	if message.IsMapEntry() {
		return
	}
	for _, field := range message.GetFields() {
		comment := cleanComment(field.GetSourceInfo().GetLeadingComments())
		name := field.GetFullyQualifiedName()
		if comment != "" {
			docs.FieldDocs[name] = comment
		}
		isAny := field.GetMessageType() != nil && field.GetMessageType().GetFullyQualifiedName() == anyFullName
		if !isAny {
			continue
		}
		// a sentence ending right after a name leaves a trailing dot in the match
		matches := extensionKindPattern.FindAllString(comment, -1)
		for i, match := range matches {
			matches[i] = strings.TrimRight(match, ".")
		}
		docs.ExtensionKinds[name] = uniqueSorted(matches)
	}
	for _, nested := range message.GetNestedMessageTypes() {
		collectMessage(nested, docs)
	}
}

// cleanComment removes the single space protoc leaves in front of each comment line.
func cleanComment(comment string) string {
	lines := strings.Split(strings.TrimRight(comment, "\n "), "\n")
	for i, line := range lines {
		lines[i] = strings.TrimRight(strings.TrimPrefix(line, " "), " ")
	}
	return strings.TrimSpace(strings.Join(lines, "\n"))
}

func uniqueSorted(values []string) []string {
	seen := map[string]bool{}
	result := []string{}
	for _, value := range values {
		if seen[value] {
			continue
		}
		seen[value] = true
		result = append(result, value)
	}
	slices.Sort(result)
	return result
}

func render(docs protoDocs) string {
	var out strings.Builder
	out.WriteString("// Generated by make generate from the proto comments (webui/protodocs), do not edit.\n")
	out.WriteString("// protobuf-es strips comments from its embedded descriptors, so the webui reads them here.\n\n")

	out.WriteString("/** Leading comment of each field, by full field name. */\n")
	out.WriteString("export const fieldDocs: Record<string, string> = {\n")
	for _, name := range sortedKeys(docs.FieldDocs) {
		fmt.Fprintf(&out, "  %s: %s,\n", jsonString(name), jsonString(docs.FieldDocs[name]))
	}
	out.WriteString("};\n\n")

	out.WriteString("/** Extension messages each google.protobuf.Any field accepts, by full field name. */\n")
	out.WriteString("export const extensionKinds: Record<string, string[]> = {\n")
	for _, name := range sortedKeys(docs.ExtensionKinds) {
		kinds := make([]string, 0, len(docs.ExtensionKinds[name]))
		for _, kind := range docs.ExtensionKinds[name] {
			kinds = append(kinds, jsonString(kind))
		}
		fmt.Fprintf(&out, "  %s: [%s],\n", jsonString(name), strings.Join(kinds, ", "))
	}
	out.WriteString("};\n\n")

	out.WriteString("/** Value the controller gives a field left empty, as a form input shows it, by full field name. */\n")
	out.WriteString("export const fieldDefaults: Record<string, string> = {\n")
	for _, name := range sortedKeys(docs.FieldDefaults) {
		fmt.Fprintf(&out, "  %s: %s,\n", jsonString(name), jsonString(docs.FieldDefaults[name]))
	}
	out.WriteString("};\n")
	return out.String()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}

func jsonString(s string) string {
	var buf bytes.Buffer
	encoder := json.NewEncoder(&buf)
	encoder.SetEscapeHTML(false)
	_ = encoder.Encode(s)
	return strings.TrimSuffix(buf.String(), "\n")
}
