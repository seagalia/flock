package main

import (
	"strings"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

var _ = Describe("collectDocs", func() {
	var docs protoDocs

	BeforeEach(func() {
		var err error
		docs, err = collectDocs()
		Expect(err).ToNot(HaveOccurred())
	})

	It("lists the extension kinds of a typed_options field", func() {
		Expect(docs.ExtensionKinds).To(HaveKeyWithValue(
			"flock.api.config.vs.v1.HttpRoutesConfig.typed_options",
			[]string{"flock.extensions.vs.f5_options.v1.VirtualServerOptions", "flock.extensions.vs.starling_options.v1.HttpOptions"},
		))
	})

	It("documents the fields of the config models", func() {
		Expect(docs.FieldDocs["flock.api.config.vip.v1.VIP.name"]).ToNot(BeEmpty())
	})

	It("gives the defaults the controller fills, as the text a form shows", func() {
		Expect(docs.FieldDefaults).To(HaveKeyWithValue("flock.api.config.core.v1.HealthCheck.timeout", "30s"))
		Expect(docs.FieldDefaults).To(HaveKeyWithValue("flock.api.config.core.v1.HealthCheck.unhealthy_threshold", "3"))
		Expect(docs.FieldDefaults).To(HaveKeyWithValue("flock.api.config.core.v1.HttpHealthCheck.path", "/"))
		Expect(docs.FieldDefaults).To(HaveKeyWithValue("flock.api.config.backend.v1.Backend.refresh_rate", "5s"))
	})

	It("leaves out a default copied from another field", func() {
		Expect(docs.FieldDefaults).ToNot(HaveKey("flock.api.config.core.v1.HealthCheck.unhealthy_interval"))
	})

	It("leaves out the defaults that are not one value", func() {
		Expect(docs.FieldDefaults).ToNot(HaveKey("flock.api.config.backend.v1.Backend.health_check"))
		Expect(docs.FieldDefaults).ToNot(HaveKey("flock.api.config.route.v1.VirtualHost.domains"))
	})

	It("renders a deterministic file with a generated header", func() {
		first := render(docs)
		Expect(first).To(HavePrefix("// Generated by make generate"))
		Expect(first).To(Equal(render(docs)))
		Expect(strings.Count(first, "export const")).To(Equal(3))
	})
})
