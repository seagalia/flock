function pick(list: string[]): string {
  const [random] = crypto.getRandomValues(new Uint32Array(1));
  return list[random % list.length];
}

// proposeName gives a random name, a new resource then always starts with one the user may keep
export function proposeName(): string {
  return `${pick(birds)}-${pick(towns)}`;
}

// isProposedName tells whether the name is still one the dashboard proposed, the user may have typed over it
export function isProposedName(name: string): boolean {
  const bird = birds.find((one) => name.startsWith(one + '-'));
  return bird !== undefined && towns.includes(name.slice(bird.length + 1));
}
